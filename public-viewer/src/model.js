// Pure: everything the viewer works out from a public export (format v1),
// with no DOM. Tested in test/unit/public-viewer/model.test.js.

export const SPECTRUM = ['captured', 'digital', 'assisted', 'hybrid', 'synthetic', 'unknown'];

// What each spectrum position means, as the end of a sentence.
const SEEN = {
	captured: 'was filmed with a camera',
	digital: 'was made on a computer without AI',
	assisted: 'was adjusted with help from AI',
	hybrid: 'combines real footage with AI-generated material',
	synthetic: 'was generated by AI',
	unknown: 'is of unknown origin'
};
const HEARD = {
	captured: 'was recorded with a microphone',
	digital: 'was made on a computer without AI',
	assisted: 'was cleaned up with help from AI',
	hybrid: 'combines real recordings with AI-generated sound',
	synthetic: 'was generated by AI',
	unknown: 'is of unknown origin'
};

/** "1:05", or "1:02:05" past an hour. */
export function clock(seconds) {
	const s = Math.max(0, Math.floor(Number(seconds) || 0));
	const h = Math.floor(s / 3600);
	const m = Math.floor((s % 3600) / 60);
	const r = String(s % 60).padStart(2, '0');
	return h ? `${h}:${String(m).padStart(2, '0')}:${r}` : `${m}:${r}`;
}

/** Index of the section playing at `t` (sections tile the film), or -1. */
export function sectionAt(intervals, t) {
	let lo = 0;
	let hi = (intervals?.length || 0) - 1;
	while (lo <= hi) {
		const mid = (lo + hi) >> 1;
		const s = intervals[mid];
		if (t < s.start) hi = mid - 1;
		else if (t >= s.end) lo = mid + 1;
		else return mid;
	}
	// The very end of the film belongs to the last section.
	const last = intervals?.[intervals.length - 1];
	return last && t >= last.end && t - last.end < 0.5 ? intervals.length - 1 : -1;
}

/**
 * A lane's share of time by spectrum position, in spectrum order, then
 * `mixed` (two or more positions at once) and `gap` (nothing), largest
 * shares rounded so they add up to 100.
 */
export function laneShares(lane) {
	if (!lane) return [];
	const rows = SPECTRUM
		.filter(id => (lane.byPosition?.[id]?.percent || 0) > 0)
		.map(id => ({ id, percent: lane.byPosition[id].percent, seconds: lane.byPosition[id].seconds }));
	if ((lane.mixed?.percent || 0) > 0) rows.push({ id: 'mixed', percent: lane.mixed.percent, seconds: lane.mixed.seconds });
	if ((lane.gap?.percent || 0) > 0) rows.push({ id: 'gap', percent: lane.gap.percent, seconds: lane.gap.seconds });
	return withRoundedPercents(rows);
}

// Largest-remainder rounding so the whole numbers shown add up to 100.
function withRoundedPercents(rows) {
	const total = rows.reduce((n, r) => n + r.percent, 0);
	if (!total) return rows.map(r => ({ ...r, rounded: 0 }));
	const scaled = rows.map(r => (r.percent / total) * 100);
	const floors = scaled.map(Math.floor);
	let left = 100 - floors.reduce((a, b) => a + b, 0);
	const order = scaled.map((v, i) => [v - floors[i], i]).sort((a, b) => b[0] - a[0]);
	for (const [, i] of order) { if (left <= 0) break; floors[i]++; left--; }
	return rows.map((r, i) => ({ ...r, rounded: floors[i] }));
}

const NOUN = {
	picture: { captured: 'camera footage', digital: 'computer-made graphics', assisted: 'AI-adjusted footage', hybrid: 'part-generated footage', synthetic: 'AI-generated imagery', unknown: 'material of unknown origin' },
	audio: { captured: 'recorded sound', digital: 'computer-made sound', assisted: 'AI-cleaned sound', hybrid: 'part-generated sound', synthetic: 'AI-generated sound', unknown: 'sound of unknown origin' }
};

// When one combination makes up most of a lane's mixed time, name it:
// "layers recorded sound with AI-generated sound". Otherwise null.
export function mixSentence(lane, kind = 'picture') {
	const combos = Object.entries(lane?.mixed?.combos || {});
	const total = lane?.mixed?.seconds || combos.reduce((n, [, s]) => n + (s.seconds || 0), 0);
	if (!combos.length || !total) return null;
	const [key, top] = combos.sort((a, b) => (b[1].seconds || 0) - (a[1].seconds || 0))[0];
	if ((top.seconds || 0) / total < 0.6) return null;
	const nouns = key.split('+').sort((a, b) => SPECTRUM.indexOf(a) - SPECTRUM.indexOf(b)).map(p => NOUN[kind === 'audio' ? 'audio' : 'picture'][p] || p);
	return `layers ${nouns.slice(0, -1).join(', ')} with ${nouns.at(-1)}`;
}

/**
 * Plain-language summary of one lane, the two largest shares and the rest:
 * "Half of what you see was filmed with a camera; 13% was generated by AI;
 * the other 37% is a mix of other kinds."
 */
export function laneSentence(lane, kind = 'picture') {
	const words = kind === 'audio' ? HEARD : SEEN;
	const what = kind === 'audio' ? 'you hear' : 'you see';
	const rows = laneShares(lane).filter(r => r.rounded > 0 && r.id !== 'gap');
	if (!rows.length) return kind === 'audio' ? 'There is no sound.' : 'There is no picture.';
	const sorted = [...rows].sort((a, b) => b.rounded - a.rounded);
	const mixedPhrase = mixSentence(lane, kind) || (kind === 'audio' ? 'layers more than one kind at once, such as music under a voice' : 'layers more than one kind at once, such as a title over footage');
	const phrase = (r) => (r.id === 'mixed' ? mixedPhrase : words[r.id]);
	const [first, second, ...rest] = sorted;
	if (first.rounded === 100 && first.id !== 'mixed') return `Everything ${what} ${phrase(first)}.`;
	const lead = first.rounded === 50 ? `Half of what ${what}` : first.rounded > 50 ? `Most of what ${what} (${first.rounded}%)` : `${first.rounded}% of what ${what}`;
	const restShare = rest.reduce((n, r) => n + r.rounded, 0);
	const tail = rest.length === 1 ? `; ${rest[0].rounded}% ${phrase(rest[0])}` : restShare ? `; the other ${restShare}% is a mix of other kinds` : '';
	return `${lead} ${phrase(first)}${second ? `; ${second.rounded}% ${phrase(second)}` : ''}${tail}.`;
}

/** The share of a lane in which generative AI plays any part (assisted, hybrid, synthetic). */
export function aiShare(lane) {
	if (!lane) return 0;
	let seconds = 0;
	let total = 0;
	for (const s of lane.intervals || []) {
		const len = (s.end ?? 0) - (s.start ?? 0);
		total += len;
		if (s.positions.some(p => p === 'assisted' || p === 'hybrid' || p === 'synthetic')) seconds += len;
	}
	return total ? Math.round((seconds / total) * 100) : 0;
}

/** The ingredients playing in a section, top track first, with their class labels. */
export function sectionDetail(section, exp) {
	if (!section) return null;
	const byRef = new Map((exp.ingredients || []).map(i => [i.ref, i]));
	const classes = exp.vocabulary?.classes || {};
	const positions = new Map((exp.vocabulary?.positions || []).map(p => [p.id, p]));
	return {
		start: section.start,
		end: section.end,
		positions: section.positions.map(id => ({ id, label: positions.get(id)?.label || id })),
		mixed: new Set(section.positions).size > 1,
		ingredients: section.refs.map(r => byRef.get(r)).filter(Boolean).map(i => ({ ...i, classLabel: classes[i.originClass]?.label || i.originClass })),
		untracked: section.untracked || 0
	};
}

/** Ingredients grouped by spectrum position, in spectrum order, longest-used first. */
export function ingredientsBySpectrum(exp) {
	const groups = new Map(SPECTRUM.map(id => [id, []]));
	for (const i of exp.ingredients || []) (groups.get(i.position) || groups.get('unknown')).push(i);
	return [...groups.entries()]
		.filter(([, list]) => list.length)
		.map(([id, list]) => ({ id, ingredients: list.sort((a, b) => (b.pictureSeconds + b.audioSeconds) - (a.pictureSeconds + a.audioSeconds)) }));
}

/** Where an ingredient's provenance comes from, in a sentence. */
export function ingredientProvenance(i) {
	if (i.credentialsInSignedFile === 'present') {
		return `Carries its own Content Credentials${i.signerName ? `, signed by ${i.signerName}` : ''}, kept inside the signed film.`;
	}
	if (i.fileCredentials === 'present') return `Had its own Content Credentials${i.signerName ? `, signed by ${i.signerName}` : ''}.`;
	if (i.fileCredentials === 'unreadable') return 'Carries Content Credentials that could not be read.';
	return i.classSetBy === 'creator' ? 'No Content Credentials of its own: the creator states how it was made.' : 'No Content Credentials of its own: classified from its metadata.';
}

/** The signature's result in plain words: { tone: good|caution|bad, headline, detail }. */
export function signatureVerdict(sig) {
	const who = sig?.signer?.commonName || 'an unnamed certificate';
	switch (sig?.status) {
		case 'valid':
			return { tone: 'good', headline: 'Signature verified', detail: `Signed by ${who}. The film has not changed since it was signed, and the signer is on the Content Credentials trust list.` };
		case 'unrecognised_issuer':
			return { tone: 'caution', headline: 'Signature checks out; signer not yet on the trust list', detail: `Signed by ${who}. The film has not changed since it was signed. The certificate is not on the public Content Credentials trust list, so verification tools will name the signer as unrecognised.` };
		case 'hash_mismatch':
			return { tone: 'bad', headline: 'Content does not match its signature', detail: 'The file changed after it was signed, or the tool that checked it could not read that kind of hash.' };
		case 'invalid':
			return { tone: 'bad', headline: 'Signature did not validate', detail: `Failures: ${(sig.failures || []).join(', ') || 'unspecified'}.` };
		default:
			return { tone: 'bad', headline: 'No Content Credentials', detail: 'The signed file carried no credentials when it was checked.' };
	}
}

/** "a1b2 c3d4 ..." for reading a hash aloud or by eye. */
export function groupHash(hex, size = 4) {
	return String(hex || '').match(new RegExp(`.{1,${size}}`, 'g'))?.join(' ') || '';
}

export function formatBytes(n) {
	if (!n) return '';
	if (n >= 1e9) return `${(n / 1e9).toFixed(2)} GB`;
	if (n >= 1e6) return `${(n / 1e6).toFixed(1)} MB`;
	return `${Math.max(1, Math.round(n / 1e3))} KB`;
}

/** Checks the parts of the export the viewer relies on; throws a readable error. */
export function assertViewable(exp) {
	if (!exp || exp.format !== 'provenance-tracker.public-export') throw new Error('This is not a provenance tracker public export.');
	if (exp.formatVersion !== 1) throw new Error(`This viewer reads export format 1, not ${exp.formatVersion}.`);
	if (!exp.composition?.picture?.intervals) throw new Error('The export has no picture timeline.');
	return exp;
}
