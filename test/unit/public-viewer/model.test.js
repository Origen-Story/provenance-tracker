import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import {
	clock, sectionAt, laneShares, laneSentence, mixSentence, aiShare, sectionDetail, ingredientsBySpectrum,
	ingredientProvenance, signatureVerdict, groupHash, formatBytes, assertViewable
} from '../../../public-viewer/src/model.js';
import { validate } from '../../helpers/json-schema-lite.js';

const ROOT = path.resolve(import.meta.dirname, '..', '..', '..');
const read = (p) => JSON.parse(readFileSync(path.join(ROOT, p), 'utf8'));
const example = read('public-viewer/example/example.provenance.json');

describe('the committed example export', () => {
	it('matches the public export schema', () => {
		expect(validate(read('schemas/public-export.v1.schema.json'), example)).toEqual([]);
	});
	it('is made up: no drive paths or real-looking folders', () => {
		const json = JSON.stringify(example);
		expect(json).not.toMatch(/[A-Za-z]:\\\\|\/Users\/|\/home\//);
	});
});

// The DOM modules are not imported by any test or by the app build, so at
// least make sure they parse.
describe('viewer modules', () => {
	for (const file of ['public-viewer/src/viewer.js', 'public-viewer/src/players.js', 'public-viewer/src/model.js']) {
		it(`${file} is valid JavaScript`, () => {
			const r = spawnSync(process.execPath, ['--check', path.join(ROOT, file)], { encoding: 'utf8' });
			expect(r.stderr).toBe('');
			expect(r.status).toBe(0);
		});
	}
});

describe('clock', () => {
	it('formats minutes and hours', () => {
		expect(clock(0)).toBe('0:00');
		expect(clock(65.9)).toBe('1:05');
		expect(clock(3725)).toBe('1:02:05');
		expect(clock(undefined)).toBe('0:00');
	});
});

describe('sectionAt', () => {
	const s = [{ start: 0, end: 2 }, { start: 2, end: 5 }, { start: 5, end: 9 }];
	it('finds the section playing at a time', () => {
		expect(sectionAt(s, 0)).toBe(0);
		expect(sectionAt(s, 1.999)).toBe(0);
		expect(sectionAt(s, 2)).toBe(1);
		expect(sectionAt(s, 8.5)).toBe(2);
	});
	it('keeps the last section at the very end and nothing far past it', () => {
		expect(sectionAt(s, 9)).toBe(2);
		expect(sectionAt(s, 20)).toBe(-1);
		expect(sectionAt([], 1)).toBe(-1);
	});
});

describe('laneShares and laneSentence', () => {
	const lane = {
		byPosition: { synthetic: { seconds: 30, percent: 33.4 }, captured: { seconds: 55, percent: 55.3 } },
		mixed: { seconds: 10, percent: 11.3 }, gap: { seconds: 0, percent: 0 }
	};
	it('lists shares in spectrum order with whole numbers that add up to 100', () => {
		const rows = laneShares(lane);
		expect(rows.map(r => r.id)).toEqual(['captured', 'synthetic', 'mixed']);
		expect(rows.reduce((n, r) => n + r.rounded, 0)).toBe(100);
	});
	it('says it in plain words, largest first', () => {
		// 55.3 / 33.4 / 11.3: the spare point goes to the largest remainder (.4), so the three add up to 100.
		expect(laneSentence(lane, 'picture')).toBe('Most of what you see (55%) was filmed with a camera; 34% was generated by AI; 11% layers more than one kind at once, such as a title over footage.');
	});
	it('handles a lane that is all one kind, and sound', () => {
		const all = { byPosition: { captured: { seconds: 10, percent: 100 } }, mixed: { percent: 0 }, gap: { percent: 0 } };
		expect(laneSentence(all, 'audio')).toBe('Everything you hear was recorded with a microphone.');
		expect(laneSentence({ byPosition: {}, mixed: { percent: 0 }, gap: { percent: 100 } }, 'audio')).toBe('There is no sound.');
	});
	it('names the two largest shares and sums the rest', () => {
		expect(laneSentence(example.composition.picture, 'picture')).toBe('Half of what you see was filmed with a camera; 13% was generated by AI; the other 37% is a mix of other kinds.');
		expect(laneSentence(example.composition.audio, 'audio')).toBe('Half of what you hear layers recorded sound with AI-generated sound; 31% was recorded with a microphone; 19% was generated by AI.');
	});
	it('names a mix only when one combination dominates it', () => {
		const lane = (combos) => ({ mixed: { seconds: 10, combos } });
		expect(mixSentence(lane({ 'synthetic+captured': { seconds: 9 }, 'digital+captured': { seconds: 1 } }), 'picture')).toBe('layers camera footage with AI-generated imagery');
		expect(mixSentence(lane({ 'synthetic+captured': { seconds: 5 }, 'digital+captured': { seconds: 5 } }), 'picture')).toBeNull();
		expect(mixSentence(lane({}), 'audio')).toBeNull();
	});
});

describe('aiShare', () => {
	it('counts any moment where generative AI plays a part, mixed or not', () => {
		const lane = { intervals: [
			{ start: 0, end: 4, positions: ['captured'] },
			{ start: 4, end: 6, positions: ['captured', 'synthetic'] },
			{ start: 6, end: 8, positions: ['assisted'] },
			{ start: 8, end: 10, positions: ['digital'] }
		] };
		expect(aiShare(lane)).toBe(40);
	});
});

describe('sectionDetail', () => {
	it('names the ingredients playing, top track first, with class labels', () => {
		const d = sectionDetail(example.composition.picture.intervals[0], example);
		expect(d.positions.map(p => p.id)).toEqual(['digital', 'synthetic']);
		expect(d.mixed).toBe(true);
		expect(d.ingredients.map(i => [i.title, i.classLabel])).toEqual([['Opening view of the harbour', 'AI-generated']]);
		expect(d.untracked).toBe(1);
		expect(sectionDetail(undefined, example)).toBeNull();
	});
});

describe('ingredientsBySpectrum', () => {
	it('groups in spectrum order, longest-used first', () => {
		const groups = ingredientsBySpectrum(example);
		expect(groups.map(g => g.id)).toEqual(['captured', 'digital', 'assisted', 'hybrid', 'synthetic', 'unknown']);
		expect(groups[0].ingredients[0].title).toBe('Interview with a stallholder');
	});
});

describe('ingredientProvenance', () => {
	it('distinguishes carried credentials, the creator’s word and metadata', () => {
		expect(ingredientProvenance({ credentialsInSignedFile: 'present', signerName: 'Cam' })).toBe('Carries its own Content Credentials, signed by Cam, kept inside the signed film.');
		expect(ingredientProvenance({ credentialsInSignedFile: 'none', fileCredentials: 'none', classSetBy: 'creator' })).toMatch(/creator states/);
		expect(ingredientProvenance({ credentialsInSignedFile: 'unknown', fileCredentials: 'none', classSetBy: 'proposal' })).toMatch(/metadata/);
	});
});

describe('signatureVerdict', () => {
	it('is honest about an issuer that is not on the trust list', () => {
		const v = signatureVerdict({ status: 'unrecognised_issuer', signer: { commonName: 'Dev' } });
		expect(v.tone).toBe('caution');
		expect(v.detail).toMatch(/has not changed/);
		expect(v.detail).toMatch(/not on the public Content Credentials trust list/);
	});
	it('flags a mismatch and an absent signature', () => {
		expect(signatureVerdict({ status: 'hash_mismatch' }).tone).toBe('bad');
		expect(signatureVerdict(undefined).headline).toBe('No Content Credentials');
	});
});

describe('small formatters', () => {
	it('groups a hash and sizes a file', () => {
		expect(groupHash('abcdef123456')).toBe('abcd ef12 3456');
		expect(formatBytes(412345678)).toBe('412.3 MB');
		expect(formatBytes(2_500_000_000)).toBe('2.50 GB');
	});
	it('rejects what it cannot show', () => {
		expect(() => assertViewable({ format: 'x' })).toThrow(/not a provenance tracker/);
		expect(() => assertViewable({ ...example, formatVersion: 2 })).toThrow(/format 1/);
		expect(assertViewable(example)).toBe(example);
	});
});
