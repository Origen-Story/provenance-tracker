describe("laneShares and laneSentence", () => {
	const lane = {
		byPosition: {
			synthetic: { seconds: 30, percent: 33.4 },
			captured: { seconds: 55, percent: 55.3 },
		},
		mixed: { seconds: 10, percent: 11.3 },
		gap: { seconds: 0, percent: 0 },
	};
	it("lists shares in spectrum order with whole numbers that add up to 100", () => {
		const rows = laneShares(lane);
		expect(rows.map((r) => r.id)).toEqual(["captured", "synthetic", "mixed"]);
		expect(rows.reduce((n, r) => n + r.rounded, 0)).toBe(100);
	});
	it("says it in plain words, largest first", () => {
		// 55.3 / 33.4 / 11.3: the spare point goes to the largest remainder (.4), so the three add up to 100.
		expect(laneSentence(lane, "picture")).toBe(
			"Most of what you see (55%) was filmed with a camera; 34% was generated by AI; 11% layers more than one kind at once, such as a title over footage.",
		);
	});
	it("handles a lane that is all one kind, and sound", () => {
		const all = {
			byPosition: { captured: { seconds: 10, percent: 100 } },
			mixed: { percent: 0 },
			gap: { percent: 0 },
		};
		expect(laneSentence(all, "audio")).toBe(
			"Everything you hear was recorded with a microphone.",
		);
		expect(
			laneSentence(
				{ byPosition: {}, mixed: { percent: 0 }, gap: { percent: 100 } },
				"audio",
			),
		).toBe("There is no sound.");
	});
	it("names the two largest shares and sums the rest", () => {
		expect(laneSentence(example.composition.picture, "picture")).toBe(
			"Half of what you see was filmed with a camera; 13% was generated by AI; the other 37% is a mix of other kinds.",
		);
		expect(laneSentence(example.composition.audio, "audio")).toBe(
			"Half of what you hear layers recorded sound with AI-generated sound; 31% was recorded with a microphone; 19% was generated by AI.",
		);
	});
	it("names a mix only when one combination dominates it", () => {
		const lane = (combos) => ({ mixed: { seconds: 10, combos } });
		expect(
			mixSentence(
				lane({
					"synthetic+captured": { seconds: 9 },
					"digital+captured": { seconds: 1 },
				}),
				"picture",
			),
		).toBe("layers camera footage with AI-generated imagery");
		expect(
			mixSentence(
				lane({
					"synthetic+captured": { seconds: 5 },
					"digital+captured": { seconds: 5 },
				}),
				"picture",
			),
		).toBeNull();
		expect(mixSentence(lane({}), "audio")).toBeNull();
	});
});

